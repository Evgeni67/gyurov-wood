export function getProduct(category: string, slug: string) {
  return products.find((p) => p.category === category && p.slug === slug);
}

export function productsIn(category: string) {
  return products.filter((p) => p.category === category);
}

export function productPath(p: Product) {
  return `/${p.category}/${p.slug}`;
}

export function related(p: Product, n = 6) {
  const same = products.filter((x) => x.category === p.category && x.id !== p.id);
  const other = products.filter((x) => x.category !== p.category);
  return [...same, ...other].slice(0, n);
}

export const formatPrice = (n: number) =>
  new Intl.NumberFormat("bg-BG", { maximumFractionDigits: 0 }).format(n) + " €";
